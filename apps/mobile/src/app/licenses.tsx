import { font, spacing, type } from '@travelog/ui';
import { useRouter } from 'expo-router';
import { useState } from 'react';
import { FlatList, Linking, Pressable, StyleSheet, Text, View } from 'react-native';

import { Between, Body, Button, Card, H1, Strong } from '@/ui/kit';
import { InsetView } from '@/ui/inset-view';
import { useTheme } from '@/ui/theme';

import packagesFile from '../../assets/licenses.json';
import noticesFile from '../../assets/notices.json';

/**
 * Licences and credits (Plan 52): the art, fonts, icons and place data the app ships,
 * with their full licence texts, then every open-source package and its licence.
 * Both files are generated by `pnpm licenses:build`.
 */
interface Notice {
  group: string;
  name: string;
  use: string;
  license: string;
  source: string;
  text: string;
}
interface Pkg {
  name: string;
  version: string;
  license: string;
  homepage: string | null;
}
const NOTICES = (noticesFile as { notices: Notice[] }).notices;
const PACKAGES = (packagesFile as { packages: Pkg[] }).packages;

function NoticeCard({ n }: { n: Notice }) {
  const t = useTheme();
  const [open, setOpen] = useState(false);
  return (
    <Card>
      <Strong>{n.name}</Strong>
      <Body muted small>
        {n.use}
      </Body>
      <Body small>Licence: {n.license}</Body>
      <Between>
        <Button
          label="Source"
          variant="link"
          onPress={() => Linking.openURL(n.source).catch(() => {})}
        />
        <Button
          label={open ? 'Hide licence' : 'Show licence'}
          variant="link"
          onPress={() => setOpen(!open)}
        />
      </Between>
      {open ? (
        <Text selectable style={[type.caption, styles.licence, { color: t.ink2 }]}>
          {n.text}
        </Text>
      ) : null}
    </Card>
  );
}

export default function Licenses() {
  const t = useTheme();
  const router = useRouter();
  const groups = [...new Set(NOTICES.map((n) => n.group))];
  return (
    <InsetView edges={['top', 'bottom']} style={{ flex: 1, backgroundColor: t.bg }}>
      <FlatList
        data={PACKAGES}
        keyExtractor={(p) => p.name}
        contentContainerStyle={styles.content}
        initialNumToRender={20}
        ListHeaderComponent={
          <View style={{ gap: spacing.lg }}>
            <Between>
              <H1>Licences and credits</H1>
              <Button label="Done" variant="link" onPress={() => router.back()} />
            </Between>
            <Body muted>TravelOG is built with work by others. Thank you to everyone below.</Body>
            {groups.map((g) => (
              <View key={g} style={{ gap: spacing.sm }}>
                <Text style={[type.label, { color: t.ink2 }]}>{g.toUpperCase()}</Text>
                {NOTICES.filter((n) => n.group === g).map((n) => (
                  <NoticeCard key={n.name} n={n} />
                ))}
              </View>
            ))}
            <Text style={[type.label, { color: t.ink2 }]}>
              OPEN-SOURCE PACKAGES · {PACKAGES.length}
            </Text>
          </View>
        }
        renderItem={({ item }) => (
          <Pressable
            accessibilityRole={item.homepage ? 'link' : undefined}
            accessibilityLabel={`${item.name} ${item.version}, ${item.license}`}
            disabled={!item.homepage}
            onPress={() => item.homepage && Linking.openURL(item.homepage).catch(() => {})}
            style={[styles.pkg, { borderColor: t.line }]}
          >
            <Text style={[type.body, { color: t.ink, flex: 1 }]} numberOfLines={1}>
              {item.name} <Text style={{ color: t.ink2 }}>{item.version}</Text>
            </Text>
            <Text style={[type.caption, { color: t.ink2, ...font('text', 600) }]}>
              {item.license}
            </Text>
          </Pressable>
        )}
      />
    </InsetView>
  );
}

const styles = StyleSheet.create({
  content: { padding: spacing.lg, gap: 0, paddingBottom: spacing.xxxl },
  licence: { fontFamily: 'monospace', marginTop: spacing.sm },
  pkg: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: spacing.md,
    paddingVertical: 10,
    borderBottomWidth: StyleSheet.hairlineWidth,
  },
});
